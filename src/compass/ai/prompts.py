DISCIPLINE_RULES = (
    "\nЭто разбор дисциплины, а не прогноз: не предсказывай цены и не говори, что купить или продать. "
    "Сопоставляй решения пользователя только с его же правилами и планами из ДАННЫХ. "
    "Не осуждай и не хвали: называй расхождение, возможную причину по данным и один конкретный вопрос к самому себе."
)


def what_changed(facts: str) -> Prompt:
    user = (
        f"ДАННЫЕ:\n{facts}\n\n"
        "ЗАДАЧА: обычными словами, что изменилось. Не больше 100 слов, без пунктов. "
        "Если ничего не изменилось — так и скажи одним предложением. Не дорисовывай события."
    )
    return Prompt("what_changed", SYSTEM + DISCIPLINE_RULES, user, facts)


def weak_assumptions(facts: str) -> Prompt:
    user = (
        f"ДАННЫЕ:\n{facts}\n\n"
        "ЗАДАЧА: скажи по-человечески, чему в этом бэктесте не стоит верить. Не больше 140 слов, без отчёта. "
        "Возьми два слабых места из ДАННЫХ, не выдумывай третье. К каждому — число из ДАННЫХ и как это проверить "
        "(отдельный период, лаборатория, спред). Прошлая удача не обещает будущую."
    )
    return Prompt("weak_assumptions", SYSTEM, user, facts)


def discipline_review(facts: str) -> Prompt:
    user = (
        f"ДАННЫЕ:\n{facts}\n\n"
        "ЗАДАЧА: скажи прямо, где человек отошёл от своих же правил. Не больше 140 слов, без морали и без пунктов «группа 1». "
        "Назови, что видно в ДАННЫХ, и один вопрос, который стоит задать себе. Если отступлений нет — так и напиши."
    )
    return Prompt("discipline_review", SYSTEM + DISCIPLINE_RULES, user, facts)


def compare_trade(facts: str) -> Prompt:
    user = (
        f"ДАННЫЕ:\n{facts}\n\n"
        "ЗАДАЧА: скажи, чем этот план отличается от прежних, обычными словами. Не больше 120 слов. "
        "Только отличия, которые видны в числах из ДАННЫХ, и один вопрос к себе. Не оценивай, хороша ли сделка. "
        "Если сравнивать почти не с чем — скажи это сразу."
    )
    return Prompt("compare_trade", SYSTEM + DISCIPLINE_RULES, user, facts)


def explain_concept(term: str, short: str, why: str, context: str | None) -> Prompt:
    data = f"Термин: {term}\nОпределение в Compass: {short}\nПочему это важно: {why}"
    if context:
        data += f"\nГде это встретилось: {context}"
    user = (
        f"ДАННЫЕ:\n{data}\n\n"
        "ЗАДАЧА: объясни слово так, чтобы было понятно без учебника. Не больше 100 слов. Своими словами, один бытовой пример "
        "без реальных цен и тикеров, и где это встретится в Compass."
    )
    return Prompt("explain_concept", SYSTEM, user, "", audit=False)
