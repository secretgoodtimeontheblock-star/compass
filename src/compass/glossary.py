def term(term_id: str) -> dict[str, str] | None:
    t = _TERMS.get(term_id)
    return None if t is None else {"id": term_id, "term": t[0], "short": t[1], "why": t[2]}


def all_terms() -> list[dict[str, str]]:
    return [term(k) for k in sorted(_TERMS, key=lambda k: _TERMS[k][0])]  # type: ignore[misc]


def concepts_for(code: str) -> list[str]:
    """Идентификаторы понятий для кода находки или предупреждения (пусто — для неизвестного кода)."""
    return list(_BY_CODE.get(code, ()))


def attach(items: list[dict[str, Any]], key: str = "code") -> list[dict[str, Any]]:
    """Добавляет к находкам поле learn — список понятий; исходные словари не меняются."""
    return [{**i, "learn": concepts_for(i.get(key, ""))} for i in items]


def validate() -> list[str]:
    """Ссылки на несуществующие понятия: нужно для теста, чтобы привязки не расходились с глоссарием."""
    return sorted({c for ids in _BY_CODE.values() for c in ids if c not in _TERMS})
